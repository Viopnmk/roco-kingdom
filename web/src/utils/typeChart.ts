/** 计算攻击属性对防御属性组合的倍率 */
export function calcEffectiveness(
  atkType: PetType,
  defTypes: PetType[]
): number {
  let m = 1;
  for (const dt of defTypes) {
    m *= TYPE_CHART[atkType]?.[dt] ?? 1;
  }
  return m;
}

/** 获取弱点/抗性 */
export function getWeaknesses(defTypes: PetType[]): { type: PetType; multiplier: number }[] {
  const result: { type: PetType; multiplier: number }[] = [];
  for (const atkType of Object.keys(TYPE_CHART) as PetType[]) {
    const m = calcEffectiveness(atkType, defTypes);
    if (m !== 1) {
      result.push({ type: atkType, multiplier: m });
    }
  }
  result.sort((a, b) => b.multiplier - a.multiplier);
  return result;
}
