def build_matrix() -> dict:
    """构建完整的倍率矩阵，缺失项填充 1.0。"""
    matrix = {}
    for atk_type in TYPES:
        row = {}
        for def_type in TYPES:
            row[def_type] = CHART.get(atk_type, {}).get(def_type, 1.0)
        matrix[atk_type] = row
    return matrix


def calc_effectiveness(atk_type: str, def_types: list[str]) -> float:
    """计算攻击属性对防御属性组合的实际倍率。
    def_types 为1-2个属性（单属性或双属性精灵）。
    """
    multiplier = 1.0
    for dt in def_types:
        m = CHART.get(atk_type, {}).get(dt, 1.0)
        multiplier *= m
    return multiplier


def get_weaknesses(def_types: list[str]) -> dict[str, float]:
    """获取某属性组合的所有弱点（>1.0）和抗性（<1.0）。"""
    result = {}
    for atk_type in TYPES:
        m = calc_effectiveness(atk_type, def_types)
        if m != 1.0:
            result[atk_type] = m
    return result


def get_all_type_data() -> dict:
    """导出所有属性克制数据。"""
    return {
        "types": TYPES,
        "chart": CHART,
        "matrix": build_matrix(),
    }


